const norm = (s: string) => s.normalize("NFD").replace(/\p{Diacritic}/gu, "").toLowerCase().replace(/[^a-z0-9 ]/g, " ").replace(/\s+/g, " ").trim();

/** Termos extras pra uma busca (os apelidos que aparecem no texto digitado) */
export function aliasTerms(q: string): string[] {
  const n = norm(q);
  if (n.length < 3) return [];
  const out: string[] = [];
  for (const [k, v] of Object.entries(ALIASES)) if (n.includes(k) || (k.startsWith(n) && n.length >= 4)) out.push(...v);
  return [...new Set(out)];
}
